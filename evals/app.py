"""📊 Evaluation Dashboard (DOCS/11 §Evaluation Dashboard).

Streamlit app with 3 tabs:

  1. Ground Truth   — review the golden dataset (15 Q&A + 6 guardrails tests)
  2. Live Pipeline  — POST each golden question to the backend & collect answers
  3. Eval Metrics   — run the 6 RAGAS experiments + Jaccard tool correctness

Run:
    streamlit run evals/app.py

Prereqs:
    * Backend running  →  uvicorn app.main:app --reload --port 8000
    * Golden dataset   →  python -m evals.golden_builder
    * JUDGE_GROQ key  →  needed for the RAGAS metrics tab (DOCS/10)
"""
from __future__ import annotations

import json
import time
from pathlib import Path

import streamlit as st

from evals.guardrails_eval import run_guardrails_eval
from evals.pipeline import run_live_pipeline

DATA_DIR = Path("evals/data")
DATASET_FILE = DATA_DIR / "golden_dataset.json"


@st.cache_data(show_spinner=False)
def load_dataset() -> dict:
    if not DATASET_FILE.exists():
        return {"samples": [], "guardrails": []}
    return json.loads(DATASET_FILE.read_text(encoding="utf-8"))


def _mean(values: list[float]) -> float:
    return round(sum(values) / len(values), 3) if values else 0.0


st.set_page_config(page_title="RAG Evaluation", page_icon="📊", layout="wide")
st.title("📊 Enterprise RAG — Evaluation Dashboard")

samples = load_dataset().get("samples", [])
guardrail_cases = load_dataset().get("guardrails", [])

tab1, tab2, tab3 = st.tabs(["1️⃣ Ground Truth", "2️⃣ Live Pipeline", "3️⃣ Eval Metrics"])

# ------------------------------------------------------------------ Tab 1
with tab1:
    st.subheader(f"Golden Dataset — {len(samples)} RAG samples")
    st.caption("Generated by `python -m evals.golden_builder` from DATA/true_data (DOCS/11 §Part 1).")
    for s in samples:
        with st.expander(f"#{s['id']} · {s['domain']} — {s['question'][:70]}"):
            st.markdown(f"**Q:** {s['question']}")
            st.markdown(f"**Reference:** {s['reference']}")
            st.markdown(f"**Expected tools:** `{s['expected_tools']}`")
            if s.get("relevant_contexts"):
                st.markdown("**Relevant context (from source doc):**")
                st.code(s["relevant_contexts"][0][:400])

    st.divider()
    st.subheader(f"Guardrails Test Cases — {len(guardrail_cases)}")
    for c in guardrail_cases:
        mark = "🚫 should block" if c["expected_blocked"] else "✅ should pass"
        st.markdown(f"- `{c['input']}` → {mark}")

# ------------------------------------------------------------------ Tab 2
with tab2:
    st.subheader("Live Pipeline (DOCS/11 §Part 2)")
    st.caption("Sends every golden question to the backend `/query` and records the real answer, sources, and detected tool.")
    if st.button("▶️ Run Live Pipeline", type="primary"):
        if not samples:
            st.error("Golden dataset empty — run `python -m evals.golden_builder` first.")
        else:
            prog = st.progress(0.0, text="Collecting live responses…")
            enriched = []
            for i, sample in enumerate(run_live_pipeline(samples, delay_s=10.0)):
                enriched.append(sample)
                prog.progress((i + 1) / len(samples), text=f"Sample {i + 1}/{len(samples)} done")
            st.session_state["enriched"] = enriched
            prog.empty()
            st.success(f"Collected {len(enriched)} live responses. Go to tab 3 to score them.")

    st.divider()
    st.subheader("Guardrails Live Check (DOCS/11 §Guardrails Evaluation)")
    if st.button("🛡️ Run Guardrails Eval"):
        if not guardrail_cases:
            st.error("No guardrails cases in dataset.")
        else:
            with st.spinner("Hitting /query with the 6 test inputs (5s delay each)…"):
                report = run_guardrails_eval(guardrail_cases, delay_s=5.0)
            c = report["confusion"]
            st.metric("Precision", report["precision"])
            st.metric("Recall", report["recall"])
            st.metric("Accuracy", report["accuracy"])
            st.markdown(f"Confusion matrix → TP {c['TP']} · TN {c['TN']} · FP {c['FP']} · FN {c['FN']}")
            for r in report["results"]:
                mark = "🚫 blocked" if r["blocked"] else "✅ passed"
                st.markdown(f"- `{r['input']}` — expected **{r['expected']}** → {mark}")
                if r.get("error"):
                    st.error(r["error"])

# ------------------------------------------------------------------ Tab 3
with tab3:
    st.subheader("RAGAS Metrics (DOCS/10, DOCS/11 §Part 4)")
    st.caption("Requires `JUDGE_GROQ` key. Judge: llama-3.1-8b-instant. Includes per-sample cooldowns to respect Groq's 6,000 TPM window.")

    source = st.radio(
        "Score which data?",
        ["Live pipeline results (run tab 2)", "Golden references only (no live answers)"],
    )

    if st.button("🧪 Run 6 Experiments", type="primary"):
        if source.startswith("Live"):
            dataset = st.session_state.get("enriched")
            if not dataset:
                st.warning("No live results yet — run the Live Pipeline tab first.")
            else:
                with st.spinner("Scoring with RAGAS… (this takes a few minutes due to cooldowns)"):
                    from evals.metrics import run_all

                    results = run_all(dataset)
                    st.session_state["results"] = results
        else:
            st.info("Use golden references as `actual_response` and relevant_contexts as retrieved contexts.")
            dataset = []
            for s in samples:
                clone = dict(s)
                clone["actual_response"] = clone.get("reference", "")
                clone["actual_contexts"] = clone.get("relevant_contexts", [])
                clone["actual_tools_called"] = clone.get("expected_tools", [])
                dataset.append(clone)
            from evals.metrics import run_all

            with st.spinner("Scoring with RAGAS… (cooldowns slow this down)"):
                results = run_all(dataset)
                st.session_state["results"] = results

    st.divider()
    results = st.session_state.get("results")
    if results:
        st.markdown("### 📈 Results (mean per metric)")
        cols = st.columns(len(results))
        for col, (name, scores) in zip(cols, results.items()):
            col.metric(name, _mean(scores))
        with st.expander("Per-sample scores"):
            st.write(results)
    else:
        st.caption("No results yet — click a button above.")